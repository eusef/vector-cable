//! Generates the theme module from `design/vector-tokens.json`: one constant
//! per colour token with its Standard and Night Ops values in 24-bit and as
//! an xterm-256 index chosen so every text pair passes 4.5:1.

#[path = "build/tokens.rs"]
mod tokens;

use std::fmt::Write as _;

/// `git <args>` in this crate's directory: stdout trimmed, or None when git
/// or the repository is unavailable (a source tarball build).
fn git(args: &[&str]) -> Option<String> {
    let out = std::process::Command::new("git")
        .args(args)
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .output()
        .ok()?;
    out.status
        .success()
        .then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// The short git hash, or empty when git or the repository is unavailable.
fn git_hash() -> String {
    git(&["rev-parse", "--short", "HEAD"]).unwrap_or_default()
}

/// Rebuild when the commit changes. `.git/HEAD` alone is not enough: it
/// usually holds "ref: refs/heads/<branch>" and stays the same across commits,
/// so the branch's ref file is watched too, with its directory (so a ref that
/// `git gc` moves into packed-refs is noticed) and packed-refs itself. Only
/// paths that exist are given to cargo: a missing watched file makes cargo
/// rebuild on every build. Paths come from git, so a worktree works.
fn watch_git_head() {
    let Some(git_dir) = git(&["rev-parse", "--absolute-git-dir"]) else {
        return;
    };
    let git_dir = std::path::PathBuf::from(git_dir);
    // The common dir holds refs for a worktree; for a plain checkout it is git_dir.
    let common = git(&["rev-parse", "--git-common-dir"])
        .map(|d| {
            let p = std::path::PathBuf::from(d);
            if p.is_absolute() {
                p
            } else {
                std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(p)
            }
        })
        .unwrap_or_else(|| git_dir.clone());
    let mut watch = vec![git_dir.join("HEAD"), common.join("packed-refs")];
    if let Some(branch) = git(&["symbolic-ref", "-q", "HEAD"]) {
        let ref_file = common.join(branch);
        if let Some(dir) = ref_file.parent() {
            watch.push(dir.to_path_buf());
        }
        watch.push(ref_file);
    }
    for path in watch.into_iter().filter(|p| p.exists()) {
        println!("cargo:rerun-if-changed={}", path.display());
    }
}

fn main() {
    println!("cargo:rustc-env=VECTORCABLE_GIT_HASH={}", git_hash());
    watch_git_head();
    let tokens_path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../design/vector-tokens.json");
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    println!("cargo:rerun-if-changed=build/tokens.rs");
    let text = std::fs::read_to_string(&tokens_path)
        .unwrap_or_else(|e| panic!("read {}: {e}", tokens_path.display()));
    let json: serde_json::Value = serde_json::from_str(&text).expect("vector-tokens.json");
    let version = json["version"].as_u64().unwrap_or(0);
    let synced = json["meta"]["synced"].as_str().unwrap_or("");
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by build.rs from design/vector-tokens.json; do not edit."
    )
    .unwrap();
    writeln!(out, "pub const TOKENS_VERSION: u64 = {version};").unwrap();
    writeln!(out, "pub const TOKENS_SYNCED: &str = {synced:?};").unwrap();
    let all = tokens::resolve_all(&json);
    for t in &all {
        let name = tokens::const_name(&t.name);
        writeln!(
            out,
            "pub const {name}: ColorToken = ColorToken {{ name: {:?}, standard: Rgb({}, {}, {}), night_ops: Rgb({}, {}, {}), standard_256: {}, night_ops_256: {} }};",
            t.name,
            t.standard.0, t.standard.1, t.standard.2,
            t.night_ops.0, t.night_ops.1, t.night_ops.2,
            t.standard_256, t.night_ops_256
        )
        .unwrap();
    }
    let list: Vec<String> = all
        .iter()
        .map(|t| format!("&{}", tokens::const_name(&t.name)))
        .collect();
    writeln!(
        out,
        "pub const ALL: &[&ColorToken] = &[{}];",
        list.join(", ")
    )
    .unwrap();
    let dest = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("theme_tokens.rs");
    std::fs::write(&dest, out).unwrap();
}
